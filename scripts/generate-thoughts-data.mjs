import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import matter from "gray-matter"

const dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(dirname, "..")
const postsDir = path.join(repoRoot, "content", "posts")
const outDir = path.join(repoRoot, "src/components/portfolio-mcp/generated")
const outFile = path.join(outDir, "thoughts-posts.ts")

const SITE_URL = "https://adityakarnam.com"

/** Posts tagged `autoblog` are machine-generated feed noise and are hidden from /blog/. */
const isAutoblog = (tags) => tags.some((tag) => String(tag).toLowerCase() === "autoblog")

const absoluteUrl = (slug) => `${SITE_URL}/${slug}/`

/**
 * MDX bodies carry imports and JSX component calls that are meaningless as prose.
 * Strip those so MCP clients receive readable markdown.
 */
const toPlainBody = (mdx) =>
  mdx
    .split("\n")
    .filter((line) => !/^\s*import\s.+from\s+["'].+["']\s*;?\s*$/.test(line))
    .join("\n")
    .replace(/<\/?[A-Z][A-Za-z0-9]*(\s[^>]*)?\/?>/g, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim()

const toExcerpt = (body, limit = 280) => {
  const prose = body
    .replace(/^#{1,6}\s.*$/gm, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[*_`>]/g, "")
    .replace(/\s+/g, " ")
    .trim()
  if (prose.length <= limit) return prose
  return `${prose.slice(0, limit).replace(/\s+\S*$/, "")}…`
}

const toIsoDate = (value) => {
  if (value instanceof Date) return value.toISOString().slice(0, 10)
  return String(value ?? "").slice(0, 10)
}

export const collectThoughtsPosts = (dir = postsDir) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true }).filter((entry) => entry.isDirectory())
  const posts = []

  for (const entry of entries) {
    const postDir = path.join(dir, entry.name)
    const sourceFile = fs.readdirSync(postDir).find((file) => file.endsWith(".mdx") || file.endsWith(".md"))
    if (!sourceFile) continue

    const { data, content } = matter(fs.readFileSync(path.join(postDir, sourceFile), "utf8"))
    const tags = (Array.isArray(data.tags) ? data.tags : []).map((tag) =>
      typeof tag === "string" ? tag : String(tag?.name ?? "")
    )
    if (isAutoblog(tags)) continue

    const slug = String(data.slug || "").replace(/^\/+|\/+$/g, "")
    if (!slug) continue

    const body = toPlainBody(content)

    posts.push({
      slug,
      title: String(data.title || slug),
      date: toIsoDate(data.date),
      description: String(data.description || "").trim() || toExcerpt(body),
      excerpt: toExcerpt(body),
      tags: tags.filter(Boolean),
      url: String(data.canonicalUrl || absoluteUrl(slug)).replace(/([^:]\/)\/+/g, "$1"),
      wordCount: body.split(/\s+/).filter(Boolean).length,
      body,
    })
  }

  return posts.sort((left, right) => right.date.localeCompare(left.date) || left.title.localeCompare(right.title))
}

const main = () => {
  const posts = collectThoughtsPosts()
  fs.mkdirSync(outDir, { recursive: true })
  fs.writeFileSync(
    outFile,
    `// Generated by scripts/generate-thoughts-data.mjs from content/posts/. Do not edit by hand.\n` +
      `import type { PortfolioThought } from "../schema"\n\n` +
      `export const THOUGHTS_POSTS: PortfolioThought[] = ${JSON.stringify(posts, null, 2)}\n`
  )
  console.log(`Wrote ${outFile} (${posts.length} posts)`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main()
}
