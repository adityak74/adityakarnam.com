#!/usr/bin/env node
// Regenerates the data behind the homepage "Pace and depth" section:
//   src/components/world-model/growth-data.ts  GitHub contributions per month (gh GraphQL)
//   src/components/world-model/posts.ts        technical posts on this site (content/posts frontmatter)
//   src/components/world-model/essays.ts       Call to Think essays (call-to-think-blog repo)
// Usage: node scripts/update-growth-data.mjs   (needs an authenticated `gh`)
// Env: CTT_DIR=/path/to/call-to-think-blog (default ../call-to-think-blog, else a shallow gh clone)
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const OUT = path.join(ROOT, "src/components/world-model")
const LOGIN = "adityak74"
const START = "2024-11-12" // first month of the chart (partial from this day)
// Personal posts kept off the chart (matched against slug or title).
const PERSONAL = ["30th-birthday", "the-motivation-from", "friday-coffee", "the-hike-to-hanuman", "Unlock Your True Purpose"]

const gh = (args) => execFileSync("gh", args, { encoding: "utf8" })
const pad = (n) => String(n).padStart(2, "0")
const json = (v) => JSON.stringify(v)

// --- GitHub contributions per month -------------------------------------------------
function contributions(from, to) {
  const q = `query($from:DateTime!,$to:DateTime!){user(login:"${LOGIN}"){contributionsCollection(from:$from,to:$to){contributionCalendar{totalContributions}}}}`
  return Number(gh(["api", "graphql", "-f", `query=${q}`, "-f", `from=${from}`, "-f", `to=${to}`, "--jq", ".data.user.contributionsCollection.contributionCalendar.totalContributions"]).trim())
}
function months() {
  const out = []
  const now = new Date()
  let y = Number(START.slice(0, 4)), m = Number(START.slice(5, 7))
  while (y < now.getUTCFullYear() || (y === now.getUTCFullYear() && m <= now.getUTCMonth() + 1)) {
    const first = out.length === 0 ? START : `${y}-${pad(m)}-01`
    const last = new Date(Date.UTC(y, m, 0)).toISOString().slice(0, 10)
    out.push([`${y}-${pad(m)}`, contributions(`${first}T00:00:00Z`, `${last}T23:59:59Z`)])
    m === 12 ? ((y += 1), (m = 1)) : (m += 1)
  }
  return out
}

// --- frontmatter helpers --------------------------------------------------------------
const field = (fm, k) => (fm.match(new RegExp(`^${k}:\\s*["']?(.*?)["']?\\s*$`, "m")) || [])[1]
const slugify = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))

function posts() {
  return walk(path.join(ROOT, "content/posts"))
    .filter((f) => /\.mdx?$/.test(f))
    .map((f) => fs.readFileSync(f, "utf8"))
    .filter((t) => t.startsWith("---"))
    .map((t) => t.split("---")[1])
    .filter((fm) => field(fm, "date") && field(fm, "draft") !== "true")
    .map((fm) => {
      const title = field(fm, "title")
      let to = field(fm, "slug") || `/${slugify(title)}`
      if (!to.endsWith("/")) to += "/"
      return { date: field(fm, "date").slice(0, 10), to, title }
    })
    .filter((p) => !PERSONAL.some((k) => p.to.includes(k) || p.title.includes(k)))
    .sort((a, b) => a.date.localeCompare(b.date))
}

function essays() {
  let dir = process.env.CTT_DIR || path.resolve(ROOT, "../call-to-think-blog")
  if (!fs.existsSync(dir)) {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "ctt-"))
    gh(["repo", "clone", `${LOGIN}/call-to-think-blog`, dir, "--", "--depth", "1", "-q"])
  }
  const blog = path.join(dir, "src/content/blog")
  return fs.readdirSync(blog)
    .filter((f) => /\.mdx?$/.test(f))
    .map((f) => ({ f, fm: fs.readFileSync(path.join(blog, f), "utf8").split("---")[1] }))
    .filter(({ fm }) => field(fm, "draft") !== "true" && field(fm, "pubDate"))
    .map(({ f, fm }) => {
      const d = new Date(`${field(fm, "pubDate")} UTC`)
      return { date: d.toISOString().slice(0, 10), slug: f.replace(/\.mdx?$/, ""), title: field(fm, "title") }
    })
    .sort((a, b) => a.date.localeCompare(b.date) || a.slug.localeCompare(b.slug))
}

// --- write ----------------------------------------------------------------------------
const today = new Date().toISOString().slice(0, 10)
const GH = months()
fs.writeFileSync(path.join(OUT, "growth-data.ts"),
  `// Generated by scripts/update-growth-data.mjs on ${today}. Do not edit by hand.\n` +
  `// GitHub contributions per month for ${LOGIN} (commits, PRs, issues, reviews) from ${START}; the last month is partial.\n` +
  `export const GH: [string, number][] = ${json(GH)}\n`)
const P = posts()
fs.writeFileSync(path.join(OUT, "posts.ts"),
  `// Generated by scripts/update-growth-data.mjs on ${today}. Technical posts on adityakarnam.com (frontmatter dates); personal posts left out.\n` +
  `export const POSTS: { date: string; to: string; title: string }[] = [\n${P.map((p) => `  { date: ${json(p.date)}, to: ${json(p.to)}, title: ${json(p.title)} },`).join("\n")}\n]\n`)
const E = essays()
fs.writeFileSync(path.join(OUT, "essays.ts"),
  `// Generated by scripts/update-growth-data.mjs on ${today}. Call to Think essays by Aditya Karnam (calltothink.com), from pubDate.\n` +
  `export const ESSAYS: { date: string; slug: string; title: string }[] = [\n${E.map((e) => `  { date: ${json(e.date)}, slug: ${json(e.slug)}, title: ${json(e.title)} },`).join("\n")}\n]\n`)

const total = GH.reduce((s, [, n]) => s + n, 0)
console.log(`months ${GH.length} (${GH[0][0]}..${GH.at(-1)[0]}), contributions ${total}, posts ${P.length}, essays ${E.length}`)
